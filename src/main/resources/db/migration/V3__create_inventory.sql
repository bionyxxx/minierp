CREATE TABLE stocks (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id      BIGINT        NOT NULL REFERENCES items (id),
    warehouse_id BIGINT        NOT NULL REFERENCES warehouses (id),
    qty          NUMERIC(18,3) NOT NULL DEFAULT 0,
    CONSTRAINT uq_stocks_item_warehouse UNIQUE (item_id, warehouse_id),
    CONSTRAINT ck_stocks_qty CHECK (qty >= 0)
);

CREATE TABLE stock_movements (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id       BIGINT        NOT NULL REFERENCES items (id),
    warehouse_id  BIGINT        NOT NULL REFERENCES warehouses (id),
    movement_type VARCHAR(10)   NOT NULL,
    qty           NUMERIC(18,3) NOT NULL,
    ref_type      VARCHAR(20)   NOT NULL,
    ref_id        BIGINT        NOT NULL,
    ref_number    VARCHAR(30)   NOT NULL,
    remark        VARCHAR(255),
    created_by    VARCHAR(50)   NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_stock_movements_type CHECK (movement_type IN ('IN', 'OUT')),
    CONSTRAINT ck_stock_movements_qty CHECK (qty > 0),
    CONSTRAINT ck_stock_movements_ref CHECK (ref_type IN ('GRN', 'DELIVERY'))
);

CREATE INDEX idx_stock_movements_item ON stock_movements (item_id);
CREATE INDEX idx_stock_movements_warehouse ON stock_movements (warehouse_id);
