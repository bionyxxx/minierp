CREATE SEQUENCE sales_order_seq START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE delivery_seq START WITH 1 INCREMENT BY 1;

CREATE TABLE sales_orders (
    id            BIGINT PRIMARY KEY DEFAULT nextval('sales_order_seq'),
    so_number     VARCHAR(30)   NOT NULL,
    customer_id   BIGINT        NOT NULL REFERENCES customers (id),
    order_date    DATE          NOT NULL,
    status        VARCHAR(20)   NOT NULL,
    total_amount  NUMERIC(18,2) NOT NULL DEFAULT 0,
    notes         VARCHAR(500),
    created_by    VARCHAR(50)   NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    approved_by   VARCHAR(50),
    approved_at   TIMESTAMP WITH TIME ZONE,
    reject_reason VARCHAR(500),
    CONSTRAINT uq_sales_orders_number UNIQUE (so_number),
    CONSTRAINT ck_sales_orders_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    CONSTRAINT ck_sales_orders_total CHECK (total_amount >= 0)
);

CREATE TABLE sales_order_lines (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sales_order_id BIGINT        NOT NULL REFERENCES sales_orders (id) ON DELETE CASCADE,
    item_id        BIGINT        NOT NULL REFERENCES items (id),
    qty            NUMERIC(18,3) NOT NULL,
    unit_price     NUMERIC(18,2) NOT NULL,
    line_total     NUMERIC(18,2) NOT NULL,
    CONSTRAINT ck_sales_order_lines_qty CHECK (qty > 0),
    CONSTRAINT ck_sales_order_lines_price CHECK (unit_price >= 0),
    CONSTRAINT ck_sales_order_lines_total CHECK (line_total >= 0)
);

CREATE TABLE deliveries (
    id             BIGINT PRIMARY KEY DEFAULT nextval('delivery_seq'),
    delivery_number VARCHAR(30)  NOT NULL,
    sales_order_id BIGINT        NOT NULL REFERENCES sales_orders (id),
    warehouse_id   BIGINT        NOT NULL REFERENCES warehouses (id),
    delivery_date  DATE          NOT NULL,
    status         VARCHAR(20)   NOT NULL,
    notes          VARCHAR(500),
    created_by     VARCHAR(50)   NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    approved_by    VARCHAR(50),
    approved_at    TIMESTAMP WITH TIME ZONE,
    reject_reason  VARCHAR(500),
    CONSTRAINT uq_deliveries_number UNIQUE (delivery_number),
    CONSTRAINT ck_deliveries_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED'))
);

CREATE TABLE delivery_lines (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    delivery_id BIGINT        NOT NULL REFERENCES deliveries (id) ON DELETE CASCADE,
    item_id     BIGINT        NOT NULL REFERENCES items (id),
    qty         NUMERIC(18,3) NOT NULL,
    CONSTRAINT ck_delivery_lines_qty CHECK (qty > 0)
);
