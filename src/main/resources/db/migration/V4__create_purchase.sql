CREATE SEQUENCE purchase_order_seq START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE goods_receipt_seq START WITH 1 INCREMENT BY 1;

CREATE TABLE purchase_orders (
    id            BIGINT PRIMARY KEY DEFAULT nextval('purchase_order_seq'),
    po_number     VARCHAR(30)   NOT NULL,
    supplier_id   BIGINT        NOT NULL REFERENCES suppliers (id),
    order_date    DATE          NOT NULL,
    status        VARCHAR(20)   NOT NULL,
    total_amount  NUMERIC(18,2) NOT NULL DEFAULT 0,
    notes         VARCHAR(500),
    created_by    VARCHAR(50)   NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    approved_by   VARCHAR(50),
    approved_at   TIMESTAMP WITH TIME ZONE,
    reject_reason VARCHAR(500),
    CONSTRAINT uq_purchase_orders_number UNIQUE (po_number),
    CONSTRAINT ck_purchase_orders_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    CONSTRAINT ck_purchase_orders_total CHECK (total_amount >= 0)
);

CREATE TABLE purchase_order_lines (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_order_id BIGINT        NOT NULL REFERENCES purchase_orders (id) ON DELETE CASCADE,
    item_id           BIGINT        NOT NULL REFERENCES items (id),
    qty               NUMERIC(18,3) NOT NULL,
    unit_price        NUMERIC(18,2) NOT NULL,
    line_total        NUMERIC(18,2) NOT NULL,
    CONSTRAINT ck_purchase_order_lines_qty CHECK (qty > 0),
    CONSTRAINT ck_purchase_order_lines_price CHECK (unit_price >= 0),
    CONSTRAINT ck_purchase_order_lines_total CHECK (line_total >= 0)
);

CREATE TABLE goods_receipts (
    id                BIGINT PRIMARY KEY DEFAULT nextval('goods_receipt_seq'),
    grn_number        VARCHAR(30)   NOT NULL,
    purchase_order_id BIGINT        NOT NULL REFERENCES purchase_orders (id),
    warehouse_id      BIGINT        NOT NULL REFERENCES warehouses (id),
    receipt_date      DATE          NOT NULL,
    status            VARCHAR(20)   NOT NULL,
    notes             VARCHAR(500),
    created_by        VARCHAR(50)   NOT NULL,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    approved_by       VARCHAR(50),
    approved_at       TIMESTAMP WITH TIME ZONE,
    reject_reason     VARCHAR(500),
    CONSTRAINT uq_goods_receipts_number UNIQUE (grn_number),
    CONSTRAINT ck_goods_receipts_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED'))
);

CREATE TABLE goods_receipt_lines (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    goods_receipt_id BIGINT        NOT NULL REFERENCES goods_receipts (id) ON DELETE CASCADE,
    item_id          BIGINT        NOT NULL REFERENCES items (id),
    qty              NUMERIC(18,3) NOT NULL,
    CONSTRAINT ck_goods_receipt_lines_qty CHECK (qty > 0)
);
